"""
Страницы для длинных списков (решение от 26.11).

Зачем: под одним сообщением Telegram показывает не больше ~100 кнопок.
В полном списке блюд на каждое блюдо 4 кнопки (название, −, количество, +),
так что уже на 25 блюдах экран перестал бы открываться. Поэтому любой
список, который может вырасти, показывается страницами.

Пока элементов меньше, чем помещается на одну страницу, стрелок
«← 1/3 →» и кнопки поиска нет — экран выглядит как обычно.

Хочешь поменять, сколько помещается на страницу, — меняй числа здесь.
"""

from typing import TypeVar

T = TypeVar("T")

CLIENT_LIST_PAGE = 12  # полный список блюд лавки у клиента
STOCK_PAGE = 12  # «🧺 Вне лавки» у клиента
CAROUSEL_LIST_BUTTON_FROM = 9  # кнопка «📋 Весь список» в карусели — от 9 блюд
CATALOG_PAGE = 10  # каталог шефа и выбор блюда в лавку / вне лавки
ORDERS_PAGE = 15  # заказы у шефа
LEFTOVERS_PAGE = 12  # «Лишние порции» у шефа
RECENT_COUNT = 8  # сколько «недавних» блюд показывать сверху каталога


def page_of(items: list[T], page: int, size: int) -> tuple[list[T], int, int]:
    """
    Вырезать одну страницу из списка.

    Возвращает (элементы страницы, номер страницы, всего страниц).
    Номер страницы «поправляется», если он вышел за границы: например,
    список укоротился, а кнопка осталась от старой страницы 3 из 3.
    """
    pages = max(1, (len(items) + size - 1) // size)  # деление с округлением вверх
    page = min(max(page, 0), pages - 1)
    start = page * size
    return items[start : start + size], page, pages
